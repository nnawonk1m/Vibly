/* ================================ FFT ==================================== */
static float am_hann[AM_FRAME_LEN];
static float am_cos[AM_NFFT/2], am_sin[AM_NFFT/2];
static uint16_t am_rev[AM_NFFT];
static float am_re[AM_NFFT], am_im[AM_NFFT];

static void am_init(void)
{
    for (int i = 0; i < AM_FRAME_LEN; i++)
        am_hann[i] = 0.5f - 0.5f * cosf(2.0f*(float)M_PI*i/(AM_FRAME_LEN-1));
    for (int i = 0; i < AM_NFFT/2; i++) {
        am_cos[i] =  cosf(-2.0f*(float)M_PI*i/AM_NFFT);
        am_sin[i] =  sinf(-2.0f*(float)M_PI*i/AM_NFFT);
    }
    int bits = 0; while ((1 << bits) < AM_NFFT) bits++;
    for (int i = 0; i < AM_NFFT; i++) {
        unsigned r = 0, x = i;
        for (int b = 0; b < bits; b++) { r = (r << 1) | (x & 1); x >>= 1; }
        am_rev[i] = (uint16_t)r;
    }
}

static void am_fft(void)
{
    for (int i = 0; i < AM_NFFT; i++) {
        int j = am_rev[i];
        if (j > i) {
            float t = am_re[i]; am_re[i] = am_re[j]; am_re[j] = t;
            t = am_im[i]; am_im[i] = am_im[j]; am_im[j] = t;
        }
    }
    for (int len = 2; len <= AM_NFFT; len <<= 1) {
        int half = len >> 1, step = AM_NFFT / len;
        for (int i = 0; i < AM_NFFT; i += len) {
            for (int k = 0; k < half; k++) {
                float wr = am_cos[k*step], wi = am_sin[k*step];
                int a = i + k, b = a + half;
                float xr = am_re[b]*wr - am_im[b]*wi;
                float xi = am_re[b]*wi + am_im[b]*wr;
                am_re[b] = am_re[a] - xr; am_im[b] = am_im[a] - xi;
                am_re[a] += xr;           am_im[a] += xi;
            }
        }
    }
}

/* ============================== MFE ====================================== */
static void am_mfe(const int16_t *pcm, float *feat)
{
    const float *mw;
    for (int f = 0; f < AM_FRAMES; f++) {
        const int16_t *src = pcm + f*AM_FRAME_HOP;
        for (int i = 0; i < AM_FRAME_LEN; i++) {
            am_re[i] = ((float)src[i] * (1.0f/32768.0f)) * am_hann[i];
            am_im[i] = 0.0f;
        }
        for (int i = AM_FRAME_LEN; i < AM_NFFT; i++) { am_re[i]=0.0f; am_im[i]=0.0f; }
        am_fft();

        mw = AM_MEL_W;
        for (int m = 0; m < AM_MELS; m++) {
            int s = AM_MEL_START[m], n = AM_MEL_LEN[m];
            float acc = 0.0f;
            for (int k = 0; k < n; k++) {
                int b = s + k;
                float p = (am_re[b]*am_re[b] + am_im[b]*am_im[b]) * (1.0f/AM_NFFT);
                acc += p * mw[k];
            }
            mw += n;
            float db = 10.0f * log10f(acc + AM_EPS);
            float v  = (db - AM_DB_FLOOR) / AM_DB_RANGE;
            if (v < 0.0f) v = 0.0f; else if (v > 1.0f) v = 1.0f;
            feat[f*AM_MELS + m] = v;
        }
    }
}

